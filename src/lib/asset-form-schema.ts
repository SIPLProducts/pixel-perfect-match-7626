import { z } from "zod";

export const assetSchema = z.object({
  name: z.string().trim().min(2, "Enter at least 2 characters").max(120),
  categoryId: z.string().uuid("Select a category"),
  serialNumber: z.string().trim().max(100).optional(),
  manufacturer: z.string().trim().max(100).optional(),
  model: z.string().trim().max(100).optional(),
  status: z.enum(["active", "in_stock", "assigned", "under_maintenance", "under_repair", "missing", "damaged", "retired", "disposed"]),
  condition: z.enum(["new", "good", "average", "poor", "damaged"]),
  locationId: z.string().uuid().optional(),
  departmentId: z.string().uuid().optional(),
  employeeId: z.string().uuid().optional(),
  purchaseValue: z.number().nonnegative().max(999999999999).optional(),
  currentValue: z.number().nonnegative().max(999999999999).optional(),
  plant: z.string().trim().max(100).optional(),
  companyCode: z.string().trim().max(50).optional(),
  installationDate: z.string().date().optional(),
  warrantyEnd: z.string().date().optional(),
  remarks: z.string().trim().max(1000).optional(),
  externalAssetNumber: z.string().trim().max(100).optional(),
  assetSubnumber: z.string().trim().max(100).optional(),
  depreciationKey: z.string().trim().max(100).optional(),
  depreciationStartDate: z.string().date().optional(),
  costCenter: z.string().trim().max(100).optional(),
  plannedLife: z.string().trim().max(100).optional(),
  erpLocation: z.string().trim().max(100).optional(),
  specialDepreciation: z.number().finite().optional(),
  supplier: z.string().trim().max(100).optional(),
  accumulatedDepreciation: z.number().finite().optional(),
  quantity: z.number().finite().optional(),
  wbsElement: z.string().trim().max(100).optional(),
  startingBookValue: z.number().finite().optional(),
  baseUnit: z.string().trim().max(100).optional(),
  currency: z.string().trim().max(100).optional(),
  writeUps: z.number().finite().optional(),
  transactionAcquisitionValue: z.number().finite().optional(),
  transferredAccumulatedDepreciation: z.number().finite().optional(),
  plannedDepreciation: z.number().finite().optional(),
  erpReference1: z.string().trim().max(100).optional(),
  erpReference2: z.string().trim().max(100).optional(),
  erpReference3: z.string().trim().max(100).optional(),
  erpReference4: z.string().trim().max(100).optional(),
});

export const updateAssetSchema = assetSchema.extend({ assetId: z.string().uuid() });

export function assetValues(data: z.infer<typeof assetSchema>) {
  return {
    name: data.name, category_id: data.categoryId,
    serial_number: data.serialNumber || null, manufacturer: data.manufacturer || null,
    model: data.model || null, plant: data.plant || null, company_code: data.companyCode || null,
    status: data.status, condition: data.condition,
    location_id: data.locationId || null, department_id: data.departmentId || null,
    assigned_employee_id: data.employeeId || null,
    purchase_value: data.purchaseValue ?? null, current_value: data.currentValue ?? null,
    capitalization_date: data.installationDate || null, warranty_end: data.warrantyEnd || null,
    remarks: data.remarks || null,
    external_asset_number: data.externalAssetNumber || null, asset_subnumber: data.assetSubnumber || null,
    depreciation_key: data.depreciationKey || null, depreciation_start_date: data.depreciationStartDate || null,
    cost_center: data.costCenter || null, planned_life: data.plannedLife || null, erp_location: data.erpLocation || null,
    special_depreciation: data.specialDepreciation ?? null, supplier: data.supplier || null,
    accumulated_depreciation: data.accumulatedDepreciation ?? null, quantity: data.quantity ?? null,
    wbs_element: data.wbsElement || null, starting_book_value: data.startingBookValue ?? null,
    base_unit: data.baseUnit || null, currency: data.currency || null, write_ups: data.writeUps ?? null,
    transaction_acquisition_value: data.transactionAcquisitionValue ?? null,
    transferred_accumulated_depreciation: data.transferredAccumulatedDepreciation ?? null,
    planned_depreciation: data.plannedDepreciation ?? null,
    erp_reference_1: data.erpReference1 || null, erp_reference_2: data.erpReference2 || null,
    erp_reference_3: data.erpReference3 || null, erp_reference_4: data.erpReference4 || null,
  };
}